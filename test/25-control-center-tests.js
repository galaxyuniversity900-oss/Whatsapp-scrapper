'use strict';
const assert=require('assert');
const {ControlCenter}=require('../src/36-control-center');
const cc=new ControlCenter({root:process.cwd(),dataDir:process.cwd()});
const mission=cc.mission('Diagnose server and analyze customer campaign');
assert.equal(mission.safety.executed,false);
assert.equal(mission.safety.messagesSent,0);
assert.ok(mission.steps.some(x=>x.id==='diagnostics'));
assert.ok(mission.steps.some(x=>x.id==='campaign-simulation'));
const quality=cc.dataQuality([{id:'1',name:'A',phone:'+201001234567',consent:true},{id:'2',name:'B',phone:'+201001234567',consent:true},{id:'3',name:'C',phone:'1',optOut:true}]);
assert.equal(quality.summary.duplicate,1);
assert.equal(quality.summary.optedOut,1);
assert.equal(quality.changesApplied,false);
const diff=cc.changeRadar([{id:'a',value:1},{id:'b',value:2}],[{id:'a',value:3},{id:'c',value:4}]);
assert.deepEqual(diff.counts,{before:2,after:2,added:1,removed:1,changed:1});
const opportunities=cc.opportunities([{topic:'delivery'},{topic:'delivery'},{topic:'price'}]);
assert.equal(opportunities.opportunities[0].topic,'delivery');
const simulation=cc.simulate({message:'Hello',contacts:[{phone:'+201001234567',consent:true},{phone:'+201001234567',consent:true},{phone:'+201111111111',optOut:true}]});
assert.equal(simulation.counts.eligible,1);
assert.equal(simulation.effects.messagesSent,0);
assert.ok(cc.playbooks().some(x=>x.id==='mcp-connection'));
console.log('Control Center tests passed');
