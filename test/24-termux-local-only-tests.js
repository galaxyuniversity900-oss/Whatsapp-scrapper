'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const server = fs.readFileSync(path.join(root, 'src/server.js'), 'utf8');
const webUI = fs.readFileSync(path.join(root, 'src/web/index.html'), 'utf8');
const cloudAdapter = fs.readFileSync(path.join(root, 'src/36-whatsapp-cloud-api.js'), 'utf8');
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
const setup = fs.readFileSync(path.join(root, 'scripts/termux-setup.sh'), 'utf8');
const start = fs.readFileSync(path.join(root, 'scripts/termux-start.sh'), 'utf8');

// Termux is the primary local runtime; Cloud API remains optional and opt-in.
assert.ok(server.includes("const host = '127.0.0.1';"), 'server must bind only to localhost');
assert.ok(server.includes("require('./36-whatsapp-cloud-api')"), 'optional Cloud API fallback adapter should remain available');
assert.ok(server.includes("new WhatsAppCloudApi({ audit })"), 'Cloud API fallback adapter should be instantiated without requiring credentials');
assert.ok(cloudAdapter.includes('this.enabled = false'), 'Cloud API sending must default to disabled');
assert.ok(!server.includes('graph.facebook.com'), 'the core local server must not directly call Meta Graph API');
assert.ok(webUI.includes('Backup only — Official WhatsApp Cloud API'), 'Cloud API must be visibly marked as backup only');
assert.ok(webUI.includes('WhatsApp Cloud API · backup only'), 'campaign channel option must identify Cloud API as backup only');
assert.ok(!webUI.includes('multiToken'), 'do not expose a raw Cloud API token input in the UI');
assert.equal(pkg.scripts.termux, 'node src/server.js');
assert.equal(pkg.scripts['termux:test'], 'bash test/termux-smoke.sh');
assert.ok(pkg.scripts['termux:local'].includes('test/26-consent-campaign-engine-tests.js'), 'Termux local suite must cover consent');
assert.ok(pkg.scripts['termux:local'].includes('test/27-cloud-delivery-tests.js'), 'Termux local suite must verify the optional fallback without live credentials');
assert.ok(!setup.includes('WHATSAPP_CLOUD_TOKEN'), 'Termux setup must not require Cloud API credentials');
assert.ok(!start.includes('WHATSAPP_CLOUD_TOKEN'), 'Termux startup must not require Cloud API credentials');
assert.ok(fs.existsSync(path.join(root, 'src/web/index.html')), 'web UI must exist');
assert.ok(fs.existsSync(path.join(root, 'src/renderer/index.html')), 'renderer compatibility entry must exist');
assert.ok(fs.existsSync(path.join(root, 'src/renderer/app.js')), 'renderer compatibility app must exist');
console.log('Termux local-first / Cloud API fallback checks passed');
