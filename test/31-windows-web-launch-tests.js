'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const server = fs.readFileSync(path.join(root, 'src/server.js'), 'utf8');
const html = fs.readFileSync(path.join(root, 'src/web/index.html'), 'utf8');
const launcher = fs.readFileSync(path.join(root, 'scripts/start-windows-web.ps1'), 'utf8');
const command = fs.readFileSync(path.join(root, 'start-windows-web.cmd'), 'utf8');
for (const asset of ['/app.js', '/styles.css', '/icon.svg']) assert.ok(server.includes(asset), 'server must serve ' + asset);
assert.match(server, /webAssets/);
assert.match(html, /styles\.css/);
assert.match(html, /app\.js/);
assert.match(launcher, /WA_ADMIN_PASSWORD/);
assert.match(launcher, /WA_DATA_DIR/);
assert.match(launcher, /127\.0\.0\.1/);
assert.match(launcher, /Node\.js 20/);
assert.match(command, /start-windows-web\.ps1/);
console.log('PASS Windows browser launcher and web asset route checks');
