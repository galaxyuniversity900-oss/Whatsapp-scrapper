'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..', 'src', 'web');
const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'manifest.json'), 'utf8'));
const sw = fs.readFileSync(path.join(root, 'sw.js'), 'utf8');
assert.equal(manifest.theme_color, '#111411');
assert.equal(manifest.background_color, '#111411');
assert.equal(manifest.display, 'standalone');
assert.match(html, /rel="manifest" href="\/manifest\.json"/);
assert.match(html, /beforeinstallprompt/);
assert.match(html, /appinstalled/);
assert.match(html, /serviceWorker\.register\('\/sw\.js'\)/);
assert.match(sw, /wa-workspace-shell-v2/);
assert.match(sw, /request\.method !== 'GET'/);
assert.match(sw, /url\.pathname\.startsWith\('\/api\/'\)/);
assert.match(sw, /Never cache API responses/);
assert.match(sw, /request\.mode === 'navigate'/);
assert.doesNotMatch(sw, /cache\.put\([^,]*api/i, 'API responses must never be persisted');
console.log('PASS PWA manifest, install lifecycle, offline shell, and private API cache-exclusion checks');
